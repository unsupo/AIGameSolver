def extract_dialogue(pyboy) -> str:
    """
    Reads the Pokemon Red dialogue buffer directly from Tile RAM.
    Buffer range: 0xC4A0 to 0xC507
    Text ID (HRAM): 0xFF8C
    """
    # Address for the text ID - if 0, no text is active
    text_id = pyboy.memory[0xFF8C]
    if text_id == 0:
        return ""

    # Pull the dialogue box tiles (Bottom 1/3 of the screen)
    raw_bytes = pyboy.memory[0xC4A0:0xC508]

    # Translate using character map
    result = "".join([GEN1_CHAR_MAP.get(b, "") for b in raw_bytes])

    # Clean up whitespace and return
    return result.strip()
